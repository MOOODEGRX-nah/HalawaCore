import assert from 'node:assert/strict';
globalThis.localStorage={getItem:()=>null};
const {processCpuCell,difference}=await import('../frontend/js/cpu-usage.js');
const {comparisonChart}=await import('../frontend/js/charts.js');
const row={cpu_percent:800,cpu_percent_device:50,cpu_logical_equivalents:8};
assert.match(processCpuCell(row),/50.0%/);
assert.match(processCpuCell(row),/8.00/);
assert.match(processCpuCell(row,'raw'),/800.0%/);
assert.match(processCpuCell({cpu_percent:800}),/—/);
assert.match(difference(-25,' pp'),/-25.0 pp/);
assert.match(difference(0,' pp'),/>0.0 pp/);
assert.equal(difference(null),'—');
const before=[{elapsed_seconds:2,process_cpu_percent_device:50},{elapsed_seconds:4,process_cpu_percent_device:40}];
const after=[{elapsed_seconds:2,process_cpu_percent_device:25},{elapsed_seconds:4,process_cpu_percent_device:20}];
assert.match(comparisonChart(before,after),/before-plot/);
assert.match(comparisonChart(before,after),/after-plot/);
assert.match(comparisonChart(before,after),/elapsed seconds/);
assert.match(comparisonChart([before[0]],after),/Collecting/);
console.log('CPU display, signed differences and aligned comparison-chart contracts passed.');
